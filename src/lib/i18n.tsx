interface LanguageContextType {
  lang: Language;
  setLang: (l: Language) => void;
  t: (key: keyof typeof translations.ko) => string;
}

const LanguageContext = createContext<LanguageContextType>({
  lang: "ko",
  setLang: () => {},
  t: (key) => translations.ko[key] || key,
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [lang, setLangState] = useState<Language>("ko");

  useEffect(() => {
    const saved = localStorage.getItem("mypickpdf_lang") as Language;
    if (saved && LANGUAGES.some((l) => l.code === saved)) {
      setLangState(saved);
      if (typeof document !== "undefined") {
        document.documentElement.lang = saved;
      }
    } else {
      const browserLang = navigator.language.toLowerCase();
      const matched = LANGUAGES.find(
        (l) => browserLang.startsWith(l.code.toLowerCase()) || l.code.toLowerCase().startsWith(browserLang.slice(0, 2))
      );
      const initial: Language = matched ? matched.code : "ko";
      setLangState(initial);
      if (typeof document !== "undefined") {
        document.documentElement.lang = initial;
      }
    }
  }, []);

  const setLang = (newLang: Language) => {
    setLangState(newLang);
    localStorage.setItem("mypickpdf_lang", newLang);
    if (typeof document !== "undefined") {
      document.documentElement.lang = newLang;
    }
  };

  const t = (key: keyof typeof translations.ko): string => {
    const langKey = lang === "zh-CN" || lang === "zh-TW" ? "zh" : lang;
    const dict = (translations as any)[langKey] || (translations as any)[lang] || translations.en || translations.ko;
    return dict[key] || translations.en[key] || translations.ko[key] || key;
  };

  return (
    <LanguageContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
